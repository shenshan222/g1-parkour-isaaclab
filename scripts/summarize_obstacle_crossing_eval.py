"""Create compact 4x4 Markdown summaries from obstacle crossing CSVs."""

from __future__ import annotations

import argparse
import csv
from pathlib import Path

ORDER = ("rough", "easy", "medium", "hard")
SUMMARY_METRICS = (
    ("obstacle_pass_rate", "Obstacle pass rate", "percent_or_na"),
    ("gap_pass_rate", "Gap pass rate", "percent_or_na"),
    ("stairs_pass_rate", "Stairs pass rate", "percent_or_na"),
    ("fall_before_obstacle_rate", "Fall before obstacle rate", "percent_or_na"),
    ("mean_boundary_x_m", "Mean boundary x", "float2_or_na"),
    ("mean_max_local_x_m", "Mean max local x", "float2_or_na"),
)


def _format_value(value: str, style: str) -> str:
    if value == "":
        return "N/A" if style in {"percent_or_na", "float2_or_na"} else ""
    number = float(value)
    if style == "percent_or_na":
        return f"{number * 100:.2f}%"
    if style == "float2_or_na":
        return f"{number:.2f}"
    raise ValueError(f"Unsupported format style: {style}")


def _read_rows(csv_path: Path) -> dict[tuple[str, str], dict[str, str]]:
    with csv_path.open(newline="") as f:
        rows = list(csv.DictReader(f))

    matrix: dict[tuple[str, str], dict[str, str]] = {}
    for row in rows:
        source = row.get("checkpoint_source", "")
        eval_env = row.get("eval_env", "")
        if source in ORDER and eval_env in ORDER:
            matrix[(source, eval_env)] = row
    return matrix


def _format_table(title: str, metric_key: str, style: str, matrix: dict[tuple[str, str], dict[str, str]]) -> list[str]:
    lines = [
        f"# {title}",
        "",
        "| Checkpoint source | Eval rough | Eval easy | Eval medium | Eval hard |",
        "|---|---:|---:|---:|---:|",
    ]
    for source in ORDER:
        cells = []
        for eval_env in ORDER:
            row = matrix.get((source, eval_env))
            cells.append(_format_value(row.get(metric_key, ""), style) if row else "")
        lines.append(f"| {source} | " + " | ".join(cells) + " |")
    lines.append("")
    return lines


def _write_summary(output_path: Path, matrix: dict[tuple[str, str], dict[str, str]]) -> None:
    lines: list[str] = []
    for metric_key, title, style in SUMMARY_METRICS:
        lines.extend(_format_table(title, metric_key, style, matrix))
    lines.extend(
        [
            "Note: obstacle pass is computed for gap and stairs terrain groups using base-level geometry boundaries.",
            "Gap pass requires crossing the far side of the gap plus a margin; stairs pass requires reaching the forward outer stair-field boundary.",
            "N/A means no gap/stairs boundary episode was covered for that source/eval pair.",
            "",
        ]
    )
    output_path.write_text("\n".join(lines))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--input_csv",
        type=Path,
        default=Path("results/metrics/obstacle_crossing_cross_terrain_eval.csv"),
        help="Obstacle crossing cross-terrain CSV generated by eval_cross_terrain.sh --metric obstacle.",
    )
    parser.add_argument("--output_dir", type=Path, default=Path("results/tables"))
    parser.add_argument("--output_prefix", type=str, default="obstacle_crossing_cross_terrain")
    parser.add_argument("--output_file", type=Path, default=None)
    args = parser.parse_args()

    if not args.input_csv.exists():
        raise FileNotFoundError(f"Input CSV does not exist: {args.input_csv}")

    matrix = _read_rows(args.input_csv)
    output_path = args.output_file or args.output_dir / f"{args.output_prefix}_summary.md"
    output_path.parent.mkdir(parents=True, exist_ok=True)
    _write_summary(output_path, matrix)

    print(f"Read: {args.input_csv}")
    print(f"Pairs: {len(matrix)}")
    print(f"Wrote summary: {output_path}")


if __name__ == "__main__":
    main()
