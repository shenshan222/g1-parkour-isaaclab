"""Create compact 4x4 Markdown summaries from timeout-based cross-terrain CSVs."""

from __future__ import annotations

import argparse
import csv
from pathlib import Path

ORDER = ("rough", "easy", "medium", "hard")
SUMMARY_METRICS = (
    ("timeout_rate", "Timeout rate", "percent"),
    ("mean_velocity_tracking_error", "XY velocity tracking error", "float3"),
)


def _format_value(value: str, style: str) -> str:
    if value == "":
        return ""
    number = float(value)
    if style == "percent":
        return f"{number * 100:.2f}%"
    if style == "float3":
        return f"{number:.3f}"
    raise ValueError(f"Unsupported format style: {style}")


def _read_rows(csv_path: Path) -> dict[tuple[str, str], dict[str, str]]:
    with csv_path.open(newline="") as f:
        rows = list(csv.DictReader(f))

    matrix: dict[tuple[str, str], dict[str, str]] = {}
    for row in rows:
        source = row.get("checkpoint_source", "")
        eval_env = row.get("eval_env", "")
        if not source or not eval_env:
            run_name = row.get("run_name", "")
            if "_to_" in run_name:
                source, eval_env = run_name.split("_to_", 1)
        if source in ORDER and eval_env in ORDER:
            matrix[(source, eval_env)] = row
    return matrix


def _format_table(
    title: str,
    metric_key: str,
    style: str,
    matrix: dict[tuple[str, str], dict[str, str]],
) -> list[str]:
    lines = [
        f"# {title}",
        "",
        "| Checkpoint source | Eval rough | Eval easy | Eval medium | Eval hard |",
        "|---|---:|---:|---:|---:|",
    ]
    for source in ORDER:
        cells = []
        for eval_env in ORDER:
            row = matrix.get((source, eval_env))
            cells.append(_format_value(row.get(metric_key, ""), style) if row else "")
        lines.append(f"| {source} | " + " | ".join(cells) + " |")
    lines.append("")
    return lines


def _write_summary(output_path: Path, matrix: dict[tuple[str, str], dict[str, str]]) -> None:
    lines: list[str] = []
    for metric_key, title, style in SUMMARY_METRICS:
        lines.extend(_format_table(title, metric_key, style, matrix))
    lines.extend(
        [
            "Note: fall rate is omitted because timeout and fall outcomes are complementary in this evaluator.",
            "",
        ]
    )
    output_path.write_text("\n".join(lines))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--input_csv",
        type=Path,
        default=Path("results/metrics/timeout_cross_terrain_eval.csv"),
        help="Cross-terrain evaluation CSV generated by eval_timeout_cross_terrain.sh.",
    )
    parser.add_argument(
        "--output_dir",
        type=Path,
        default=Path("results/tables"),
        help="Directory for generated Markdown summary when --output_file is not set.",
    )
    parser.add_argument(
        "--output_prefix",
        type=str,
        default="timeout_cross_terrain",
        help="Filename prefix for generated summary when --output_file is not set.",
    )
    parser.add_argument(
        "--output_file",
        type=Path,
        default=None,
        help="Path for the generated Markdown summary. Defaults to <output_dir>/<output_prefix>_summary.md.",
    )
    args = parser.parse_args()

    if not args.input_csv.exists():
        raise FileNotFoundError(f"Input CSV does not exist: {args.input_csv}")

    matrix = _read_rows(args.input_csv)
    output_path = args.output_file or args.output_dir / f"{args.output_prefix}_summary.md"
    output_path.parent.mkdir(parents=True, exist_ok=True)
    _write_summary(output_path, matrix)

    print(f"Read: {args.input_csv}")
    print(f"Pairs: {len(matrix)}")
    print(f"Wrote summary: {output_path}")


if __name__ == "__main__":
    main()
