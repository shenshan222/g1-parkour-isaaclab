"""Create 4x4 Markdown tables from cross-terrain evaluation CSV."""

from __future__ import annotations

import argparse
import csv
from pathlib import Path

ORDER = ("rough", "easy", "medium", "hard")
METRICS = (
    ("success_rate", "success_rate", "Success rate", "percent"),
    ("fall_rate", "fall_rate", "Fall rate", "percent"),
    ("mean_velocity_tracking_error", "tracking_error", "XY velocity tracking error", "float3"),
)


def _format_value(value: str, style: str) -> str:
    if value == "":
        return ""
    number = float(value)
    if style == "percent":
        return f"{number * 100:.2f}%"
    if style == "float3":
        return f"{number:.3f}"
    raise ValueError(f"Unsupported format style: {style}")


def _read_rows(csv_path: Path) -> dict[tuple[str, str], dict[str, str]]:
    with csv_path.open(newline="") as f:
        rows = list(csv.DictReader(f))

    matrix: dict[tuple[str, str], dict[str, str]] = {}
    for row in rows:
        source = row.get("checkpoint_source", "")
        eval_env = row.get("eval_env", "")
        if not source or not eval_env:
            run_name = row.get("run_name", "")
            if "_to_" in run_name:
                source, eval_env = run_name.split("_to_", 1)
        if source in ORDER and eval_env in ORDER:
            matrix[(source, eval_env)] = row
    return matrix


def _write_table(
    output_path: Path,
    title: str,
    metric_key: str,
    style: str,
    matrix: dict[tuple[str, str], dict[str, str]],
) -> None:
    lines = [f"# {title}", "", "| Checkpoint source | Eval rough | Eval easy | Eval medium | Eval hard |", "|---|---:|---:|---:|---:|"]
    for source in ORDER:
        cells = []
        for eval_env in ORDER:
            row = matrix.get((source, eval_env))
            cells.append(_format_value(row.get(metric_key, ""), style) if row else "")
        lines.append(f"| {source} | " + " | ".join(cells) + " |")
    lines.append("")
    output_path.write_text("\n".join(lines))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--input_csv",
        type=Path,
        default=Path("results/metrics/cross_terrain_eval.csv"),
        help="Cross-terrain evaluation CSV generated by eval_cross_terrain.sh.",
    )
    parser.add_argument(
        "--output_dir",
        type=Path,
        default=Path("results/tables"),
        help="Directory for generated Markdown tables.",
    )
    parser.add_argument(
        "--output_prefix",
        type=str,
        default="cross_terrain",
        help="Filename prefix for generated tables.",
    )
    args = parser.parse_args()

    if not args.input_csv.exists():
        raise FileNotFoundError(f"Input CSV does not exist: {args.input_csv}")

    matrix = _read_rows(args.input_csv)
    args.output_dir.mkdir(parents=True, exist_ok=True)
    for metric_key, filename_suffix, title, style in METRICS:
        _write_table(args.output_dir / f"{args.output_prefix}_{filename_suffix}.md", title, metric_key, style, matrix)

    print(f"Read: {args.input_csv}")
    print(f"Pairs: {len(matrix)}")
    print(f"Wrote tables to: {args.output_dir}")


if __name__ == "__main__":
    main()
